-- Replace <PUBLIC_KEY> (step 7) with the key from README "Key-pair login".

USE ROLE ACCOUNTADMIN;

-- 1. Warehouse: smallest size, stops after 60 s idle so it costs almost nothing.
CREATE WAREHOUSE IF NOT EXISTS ASK_PULSE_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- 2. Database and schema
CREATE DATABASE IF NOT EXISTS ASK_PULSE;
CREATE SCHEMA IF NOT EXISTS ASK_PULSE.CORE;
USE SCHEMA ASK_PULSE.CORE;

-- 3. Tables loaded every hour from Wikipedia Pulse
CREATE TABLE IF NOT EXISTS LANGUAGE_HOURLY (
  HOUR_UTC TIMESTAMP_NTZ NOT NULL COMMENT 'Start of the UTC hour',
  LANGUAGE_CODE VARCHAR NOT NULL COMMENT 'Wikipedia language code, e.g. en, hi, te',
  LANGUAGE_NAME VARCHAR NOT NULL COMMENT 'English name, e.g. Telugu',
  NATIVE_NAME VARCHAR COMMENT 'Name in the language itself',
  TOTAL_VIEWS NUMBER NOT NULL COMMENT 'Page views from India in that hour',
  LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (HOUR_UTC, LANGUAGE_CODE)
);

CREATE TABLE IF NOT EXISTS TOP_PAGES_HOURLY (
  HOUR_UTC TIMESTAMP_NTZ NOT NULL,
  LANGUAGE_CODE VARCHAR NOT NULL,
  RANK NUMBER NOT NULL COMMENT '1 = most read page in that language and hour',
  PAGE_TITLE VARCHAR NOT NULL COMMENT 'Wikipedia page title with underscores',
  VIEWS NUMBER NOT NULL,
  LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (HOUR_UTC, LANGUAGE_CODE, RANK)
);

CREATE TABLE IF NOT EXISTS TRENDING_PAGES (
  HOUR_UTC TIMESTAMP_NTZ NOT NULL COMMENT 'Hour of the spike',
  LANGUAGE_CODE VARCHAR NOT NULL,
  PAGE_TITLE VARCHAR NOT NULL,
  VIEWS NUMBER NOT NULL COMMENT 'Views in the spike hour',
  BASELINE_AVG FLOAT COMMENT 'Average views per hour over the previous 24 hours',
  SPIKE_RATIO FLOAT COMMENT 'VIEWS / BASELINE_AVG; a page is trending at 5x or more',
  WHY_CATEGORY VARCHAR COMMENT 'AI explanation category, e.g. sports, death, film_tv_music',
  WHY_REASON_EN VARCHAR COMMENT 'AI explanation in English, grounded in news sources',
  WHY_REASON_NATIVE VARCHAR COMMENT 'AI explanation in the page language',
  WHY_CONFIDENCE VARCHAR,
  WHY_SOURCES VARIANT COMMENT 'Cited news / Wikipedia sources: [{title, url}]',
  LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (HOUR_UTC, LANGUAGE_CODE, PAGE_TITLE)
);

-- 4. Agent traces: every question asked in the app or the eval, with the result and user feedback
CREATE TABLE IF NOT EXISTS TRACES (
  TRACE_ID VARCHAR, ASKED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), SOURCE VARCHAR,
  QUESTION VARCHAR, ROUTE VARCHAR, CONFIG VARCHAR, SQL_TEXT VARCHAR, ROW_COUNT NUMBER,
  ANSWER VARCHAR, STATUS VARCHAR, ERROR VARCHAR, LATENCY_MS NUMBER, FEEDBACK VARCHAR
);

-- 5. Searchable explanations (for "why is X trending?" questions)
CREATE OR REPLACE VIEW EXPLANATIONS AS
SELECT
  t.PAGE_TITLE, t.LANGUAGE_CODE, l.LANGUAGE_NAME, t.HOUR_UTC, t.SPIKE_RATIO, t.WHY_CATEGORY,
  t.WHY_REASON_EN, TO_VARCHAR(t.WHY_SOURCES) AS SOURCES,
  REPLACE(t.PAGE_TITLE, '_', ' ') || '. ' || t.WHY_REASON_EN AS SEARCH_TEXT
FROM TRENDING_PAGES t
LEFT JOIN (SELECT DISTINCT LANGUAGE_CODE, LANGUAGE_NAME FROM LANGUAGE_HOURLY) l USING (LANGUAGE_CODE)
WHERE t.WHY_REASON_EN IS NOT NULL;

-- (Optional, paid accounts only) Cortex Search service: see sql/optional_cortex_search.sql

-- 6. Stage that holds the semantic model YAML files for Cortex Analyst
CREATE STAGE IF NOT EXISTS SEMANTIC_MODELS DIRECTORY = (ENABLE = TRUE);

-- 7. Role and service user for GitHub Actions and the app (key-pair login, no password)
CREATE ROLE IF NOT EXISTS ASK_PULSE_ROLE;
GRANT USAGE, OPERATE ON WAREHOUSE ASK_PULSE_WH TO ROLE ASK_PULSE_ROLE;
GRANT USAGE ON DATABASE ASK_PULSE TO ROLE ASK_PULSE_ROLE;
GRANT USAGE ON SCHEMA ASK_PULSE.CORE TO ROLE ASK_PULSE_ROLE;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA ASK_PULSE.CORE TO ROLE ASK_PULSE_ROLE;
GRANT CREATE TABLE ON SCHEMA ASK_PULSE.CORE TO ROLE ASK_PULSE_ROLE;  -- temp tables for loading
GRANT SELECT ON ALL VIEWS IN SCHEMA ASK_PULSE.CORE TO ROLE ASK_PULSE_ROLE;
GRANT READ, WRITE ON STAGE ASK_PULSE.CORE.SEMANTIC_MODELS TO ROLE ASK_PULSE_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ASK_PULSE_ROLE;

CREATE USER IF NOT EXISTS ASK_PULSE_SVC TYPE = SERVICE DEFAULT_ROLE = ASK_PULSE_ROLE
  DEFAULT_WAREHOUSE = ASK_PULSE_WH RSA_PUBLIC_KEY = '<PUBLIC_KEY>';
GRANT ROLE ASK_PULSE_ROLE TO USER ASK_PULSE_SVC;
GRANT ROLE ASK_PULSE_ROLE TO ROLE ACCOUNTADMIN;  -- so you can test as yourself in Snowsight

